// Tailscale Serve for the iPhone app: the GUI server holds the root (`/`) handler of its Serve
// port while it runs (RubatoTailscaleServe.ts). After a reboot the Mac Tailscale app can come up
// disconnected; upstream's start runs `tailscale serve` once, and when that fails it never starts
// its repair loop, which in any case only re-adds a root left on a dead loopback port, not a
// missing one, so the phone stayed stuck reconnecting. The hold re-checks every 15 s with
// upstream's readTailscaleServeRootHolder and re-adds a missing or dead root, leaves another live
// server's or app's root alone, and stops before upstream's release step, which turns off only a
// root route it can prove is this server's. Why: memory decisions/mobile-client.md.
