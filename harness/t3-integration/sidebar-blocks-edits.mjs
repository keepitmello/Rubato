// The sidebar's sections in the user's order.
//
// The thread list is five sections: Recent (all projects, project-rail-edits.mjs),
// the narrowed project's threads under its title, Working, Snoozed and Settled.
// Dragging a section's header moves the section, and the order is a device
// setting (client setting rubatoSidebarBlocks); Settings > Threads
// puts it back. Until moved, Recent heads the list and the project's title
// follows it: what spans every project first, then this project.
//
// - sidebar/rubatoSidebarBlocks.ts: the order, the list T3 builds laid out in
//   it, and how a slot in that list maps to a section.
// - sidebar/RubatoSidebarBlockDrag.tsx: the header drag. It is not dnd-kit's:
//   threads keep their sortable list, and a thread dropped on a header still
//   moves into that section.
// - Recent, the title and Settled's "Show more" become list markers, so the
//   thread drag's preview measures them and moves them with the rest.
// - T3's drag code read the sections top-down in one fixed order (the slot's
//   section, the pinned and inbox order, the preview, where the inbox ends,
//   the drag's top limit). Each now reads the order off the markers. The free
//   space goes above the first section after the project's threads, so
//   sections above them sit at the top and the rest at the bottom, as T3's
//   shelves do.
// Registered after section-scale-edits.mjs, whose drag-offset line it sits beside.
