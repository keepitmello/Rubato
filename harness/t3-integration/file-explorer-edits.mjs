// The file surface's explorer as an IDE file browser (VS Code, Zed).
//
// - The tree sits left of the preview and its width is dragged by its right
//   edge (fileExplorerLayout.tsx). Its toggle sits at the left end of the
//   subheader, beside it.
// - Back and forward walk the paths this panel showed (fileNavigationHistory.ts),
//   from buttons before the breadcrumbs and the mouse's side buttons.
//   Cmd+[ and Cmd+] stay with the app's thread navigation.
// - A file opened from the explorer is a preview tab: the next one replaces it.
//   Double-click (row or tab) and editing keep it (rubatoFileTabs.ts).
// - New file and folder, rename (F2), move to trash (Delete, Cmd+Backspace),
//   copy path, typed in the tree row (fileExplorerActions.tsx). Folders,
//   renames and trash go through projects.manageEntry (manageWorkspaceEntry.ts);
//   a new file through the create-only projects.createFile.
// - .DS_Store and the like are hidden, and names keep their spaces.
