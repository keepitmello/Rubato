// Chat tables fit the chat width and wrap inside their cells.
//
// T3 drew every cell on one line, cut at 24rem with an ellipsis, and let the
// table grow to its content width (min-width: max-content). Two columns of
// sentences already passed the chat width, so the table scrolled sideways and
// each cell was cut as well; a footer toggle wrapped the cells on request. A
// table that needs a sideways scroll does not read at a glance, so the table
// now takes the chat width and every cell wraps, Korean between words
// (word-break: keep-all). The scroll stays only for a column whose longest
// word is wider than its share. overflow-wrap stays normal: anywhere would let
// a column shrink to one character, as T3's own note says.
//
// With one state left the wrap toggle has nothing to switch, so it goes, and
// the copy menu keeps its place on the right.
