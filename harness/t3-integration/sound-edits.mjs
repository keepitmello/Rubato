const PLAY_OLD = [
  'export async function playNotificationSound(',
  '  kind: "completion" | "input",',
  '  shouldPlay: () => boolean,',
  ') {',
  '  if (!audioContext || audioContext.state !== "running") return;',
  '  const context = audioContext;',
  '  const url = kind === "completion" ? completionUrl : inputUrl;',
  '  try {',
  '    let buffer = buffers.get(url);',
  '    if (!buffer) {',
  '      buffer = fetch(url)',
  '        .then((response) => response.arrayBuffer())',
  '        .then((data) => context.decodeAudioData(data));',
  '      buffers.set(url, buffer);',
  '    }',
  '    const decoded = await buffer;',
  '    if (!shouldPlay() || context.state !== "running") return;',
  '    const source = context.createBufferSource();',
  '    source.buffer = decoded;',
  '    source.connect(context.destination);',
  '    source.start();',
  '  } catch {',
  '    buffers.delete(url);',
  '  }',
  '}',
].join('\n');

const PLAY_NEW = [
  '/**',
  ' * Plays the sound chosen for this kind in Settings > General > Behavior',
  ' * (rubatoNotificationSounds.ts). One that does not load, a Mac sound since',
  ' * removed or a server out of reach, falls back to T3\'s own sound for the kind.',
  ' */',
  'export async function playNotificationSound(',
  '  kind: NotificationSoundKind,',
  '  shouldPlay: () => boolean,',
  '  sound: string = selectedNotificationSound(kind),',
  ') {',
  '  if (!audioContext || audioContext.state !== "running") return;',
  '  const context = audioContext;',
  '  const decoded =',
  '    (await decodeNotificationSound(context, sound)) ??',
  '    (await decodeNotificationSound(context, defaultNotificationSound(kind)));',
  '  if (!decoded || !shouldPlay() || context.state !== "running") return;',
  '  const source = context.createBufferSource();',
  '  source.buffer = decoded;',
  '  source.connect(context.destination);',
  '  source.start();',
  '}',
  '',
  'async function decodeNotificationSound(context: AudioContext, sound: string) {',
  '  let buffer = buffers.get(sound);',
  '  if (!buffer) {',
  '    buffer = loadNotificationSound(sound).then((data) => context.decodeAudioData(data));',
  '    buffers.set(sound, buffer);',
  '  }',
  '  try {',
  '    return await buffer;',
  '  } catch {',
  '    buffers.delete(sound);',
  '    return null;',
  '  }',
  '}',
  '',
  '/** Plays a sound from the settings picker, which is a gesture, so audio can start now. */',
  'export async function previewNotificationSound(kind: NotificationSoundKind, sound: string) {',
  '  audioContext ??= new AudioContext();',
  '  await audioContext.resume().catch(() => undefined);',
  '  await playNotificationSound(kind, () => true, sound);',
  '}',
].join('\n');

