// Which sound a thread notification plays. T3 plays one fixed mp3 for a finished
// thread and another for one that needs input. Settings > General > Behavior
// gets a picker for each, under Thread notifications: T3's two sounds, or one of
// this Mac's alert sounds (/System/Library/Sounds, /Library/Sounds and
// ~/Library/Sounds), which the server lists and sends at /rubato/sounds
// (src/sounds/service.mjs, behind RubatoServiceRoute.ts). Picking a sound plays
// it once; a sound that cannot load falls back to T3's own for that kind.
