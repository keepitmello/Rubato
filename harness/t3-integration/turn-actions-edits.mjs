  '    const sendContext = composerRef.current?.getSendContext();',
  '    if (!sendContext?.providerAvailable) throw new Error("The provider is not available.");',
  '    const connection = readPreparedConnection(environmentId);',
  '    if (!connection) throw new Error("The environment is not connected.");',
  '    const threadId = activeThread.id;',
  '    const target = await messageRewindTarget(environmentId, threadId, edit.messageId);',
  '    const files = await prepareRevertedMessageAttachments({',
  '      message: {',
  '        id: original.id,',
  '        role: original.role,',
  '        text: original.text,',
  '        attachments: edit.attachments,',
  '        context: original.context,',
  '        runId: original.runId,',
  '        streaming: false,',
  '        createdAt: DateTime.formatIso(original.createdAt),',
  '        updatedAt: DateTime.formatIso(original.updatedAt),',
  '      },',
  '      environmentId,',
  '      httpBaseUrl: connection.httpBaseUrl,',
  '      createAssetUrl: createAttachmentAssetUrl,',
  '    });',
